// Package report отвечает только за представление: текст для человека,
// JSON для CI. Ничего не считает — все числа приходят готовыми из stats.
//
// В пакете четырнадцать файлов, и половина из них — секции одного текстового
// отчёта. По алфавитному списку этого не видно, поэтому вот карта.
//
// Вход:
//
//	report.go     Options и RunInfo — всё, что импортирует cmd
//	renderer.go   выбор формата по -o и две его реализации
//
// Форматы:
//
//	text.go       предстартовая шапка и порядок секций
//	json.go       машинный документ, его схема и версия
//	read.go       чтение документа обратно, для -compare
//
// Секции текстового отчёта — в том порядке, в каком они печатаются.
// Порядок задан списком sections в text.go; имена файлов его не выражают,
// ради этого карта и нужна:
//
//	partial.go     ПРЕРВАНО — если прогон оборвали
//	totals.go      счётчики исходов
//	saturation.go  упёрлись в клиента, а не в сервис
//	rate.go        достигнутая частота и предупреждение о недоборе
//	latency.go     перцентили и гистограмма распределения
//	breakdown.go   фазы соединения, коды ответов, ошибки
//	provenance.go  блок «Прогон»: чем повторить через полгода
//
// Прочее:
//
//	terminal.go    TTY, ширина, палитра ANSI
//	errwriter.go   декоратор, запоминающий первую ошибку записи
//
// Карту сторожит TestPackageMap: разойдись она с sections — тест покраснеет.
package report

import (
	"time"

	"github.com/Baklachok/loadgen/internal/runner"
)

type Options struct {
	Color    bool // раскрашивать вывод ANSI-кодами
	Width    int  // ширина терминала: под неё масштабируется гистограмма
	OpenLoop bool // печатать блок с поправкой на расписание

	// Run описывает сам прогон. Отчёт живёт дольше, чем память о том, как
	// его получили, поэтому эти поля печатаются всегда.
	Run RunInfo
}

// RunInfo — всё, что нужно, чтобы повторить прогон через полгода.
type RunInfo struct {
	Version   string
	Config    runner.Config
	Proto     string // по чему реально договорились, а не что просили
	StartedAt time.Time
}
